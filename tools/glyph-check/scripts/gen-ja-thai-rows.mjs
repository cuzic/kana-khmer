// Write public/ja-thai-rows.js: the kana table and the real th-ja phrase words, spelled by packages/ja-thai, so the page never keeps its own copy.
// Run from the repo root (tsx comes from the content package):
//   pnpm --filter content exec tsx ../../tools/glyph-check/scripts/gen-ja-thai-rows.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { renderThai } from "../../../packages/ja-thai/src/index.ts";

const ROWS = ["アイウエオ", "カキクケコ", "ガギグゲゴ", "サシスセソ", "ザジズゼゾ", "タチツテト", "ダデド", "ナニヌネノ", "ハヒフヘホ", "バビブベボ", "パピプペポ", "マミムメモ", "ヤユヨ", "ラリルレロ", "ワ"];
const rows = [];
for (const r of ROWS) for (const k of r) {
  const medial = renderThai("ノ" + k).slice(renderThai("ノ").length);
  rows.push({ kana: k, initial: renderThai(k), medial: k === "ツ" ? renderThai("ミ" + k).slice(renderThai("ミ").length) : medial, long: renderThai(k + "ー") });
}
const yoon = [];
for (const k of "キギシジチニヒビピミリ") for (const s of "ャュョ") yoon.push({ kana: k + s, initial: renderThai(k + s), medial: "", long: renderThai(k + s + "ー") });

const src = readFileSync(new URL("../../../courses/th-ja/phrases.yaml", import.meta.url), "utf8");
const prons = [...new Set([...src.matchAll(/pron:\s*"?([ァ-ヺー]+)"?/g)].map((m) => m[1]))];
const words = prons.map((p) => ({ pron: p, thai: renderThai(p) }));
writeFileSync(new URL("../public/ja-thai-rows.js", import.meta.url),
  "// generated by scripts/gen-ja-thai-rows.mjs from packages/ja-thai and courses/th-ja; do not edit\nvar JA_THAI_ROWS = " + JSON.stringify([...rows, ...yoon]) + ";\nvar JA_THAI_WORDS = " + JSON.stringify(words) + ";\n");
console.log(rows.length + yoon.length, "rows;", words.length, "words");
