// Write public/ja-khmer-rows.js from docs/ja-khmer-spec.md §5 (基本46音・濁音・半濁音・拗音), so the page never keeps its own copy of the table.
// Reuses tools/ja-khmer-spike (spec-table.mjs reads the spec; convert-spec.mjs builds the long-vowel forms).
import { writeFileSync } from "node:fs";
import { loadSpecTable } from "../../ja-khmer-spike/src/spec-table.mjs";
import { kanaToKhmerSpec, SPEC_MARKS } from "../../ja-khmer-spike/src/convert-spec.mjs";

const table = loadSpecTable();
const toKata = (s) => s.replace(/[ぁ-ゖ]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0x60));
const marks = new Set(SPEC_MARKS);
const rows = Object.entries(table).map(([kana, { c, v, sh }]) => {
  const kata = toKata(kana);
  const longA = kanaToKhmerSpec(kata + "ー", marks, "a"); // 上付き母音 + U+0304(合成グリフ)
  const longC = kanaToKhmerSpec(kata + "ー", marks, "c"); // 重ね書き(フォールバック)
  return { kana, base: c + v, sh, detail: c + v + sh, longA, longC };
});
writeFileSync(new URL("../public/ja-khmer-rows.js", import.meta.url),
  "// generated by scripts/gen-ja-khmer-rows.mjs from docs/ja-khmer-spec.md; do not edit\nvar JA_KHMER_ROWS = " + JSON.stringify(rows) + ";\n");
console.log(rows.length, "rows;", rows.filter((r) => !r.longA).length, "without long form;", rows.filter((r) => r.sh).length, "with right shoulder");
