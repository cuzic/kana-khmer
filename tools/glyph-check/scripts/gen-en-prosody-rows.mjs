// Write public/en-prosody-rows.js: sample words (text + kana) taken from tools/en-prosody-spike/out/ted.ir.json,
// so the page never keeps its own copy. Picks words so that every right-shoulder IPA letter appears at least once.
//   node tools/glyph-check/scripts/gen-en-prosody-rows.mjs
import { readFileSync, writeFileSync } from "node:fs";

const MODS = [..."ʳˡʰᶿᶞᵆᶺᶦᶷᵓᵊᵑᵈᵇᵍᶻᶾᵛᵗ"];
const SMALL = [..."ㇰㇱㇲㇳㇴㇷㇺㇻㇽ"];
const ir = JSON.parse(readFileSync(new URL("../../en-prosody-spike/out/ted.ir.json", import.meta.url), "utf8"));
const seen = new Map();
for (const ev of ir.events) for (const w of ev.words) {
  if (!w.kana) continue;
  const text = w.text.replace(/[.,!?;:"]+$/g, "");
  const key = text.toLowerCase();
  if (!seen.has(key) && ![...seen.values()].some(x => x.kana === w.kana)) seen.set(key, { text, kana: w.kana });
}
const all = [...seen.values()];
const chosen = new Map();
// 1) for every modifier, prefer a short word that uses it (up to 2 per letter)
for (const m of MODS) {
  const c = all.filter(w => w.kana.includes(m)).sort((a, b) => a.kana.length - b.kana.length).slice(0, 2);
  for (const w of c) chosen.set(w.text.toLowerCase(), w);
}
// 2) the same for small kana
for (const m of SMALL) {
  const c = all.filter(w => w.kana.includes(m)).sort((a, b) => a.kana.length - b.kana.length).slice(0, 1);
  for (const w of c) chosen.set(w.text.toLowerCase(), w);
}
// 3) fill up to 36 with the words that carry the most marks
for (const w of all.sort((a, b) => [...b.kana].filter(c => MODS.includes(c)).length - [...a.kana].filter(c => MODS.includes(c)).length)) {
  if (chosen.size >= 36) break;
  chosen.set(w.text.toLowerCase(), w);
}
const words = [...chosen.values()].slice(0, 40);
const missing = MODS.filter(m => !words.some(w => w.kana.includes(m)));
console.log(`${words.length} words; modifiers not covered by the sample: ${missing.join("") || "none"}`);
writeFileSync(new URL("../public/en-prosody-rows.js", import.meta.url),
  "// generated by scripts/gen-en-prosody-rows.mjs from tools/en-prosody-spike/out/ted.ir.json; do not edit\nvar EN_PROSODY_WORDS = " + JSON.stringify(words) + ";\n");
